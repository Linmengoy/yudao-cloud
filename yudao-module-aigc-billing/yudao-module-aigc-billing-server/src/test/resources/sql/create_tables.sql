CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_cost_record_no ON aigc_cost_record(cost_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_cost_record_task ON aigc_cost_record(task_id);

CREATE TABLE IF NOT EXISTS aigc_recharge_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recharge_no varchar(64) NOT NULL,
