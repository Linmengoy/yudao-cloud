CREATE TABLE IF NOT EXISTS aigc_wallet (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    balance decimal(18,6) NOT NULL DEFAULT 0.000000,
    frozen_balance decimal(18,6) NOT NULL DEFAULT 0.000000,
    total_recharge decimal(18,6) NOT NULL DEFAULT 0.000000,
    total_gift decimal(18,6) NOT NULL DEFAULT 0.000000,
    total_consume decimal(18,6) NOT NULL DEFAULT 0.000000,
    total_refund decimal(18,6) NOT NULL DEFAULT 0.000000,
    status int NOT NULL DEFAULT 0,
    last_trans_time datetime NULL,
    remark varchar(512) NULL,
    creator varchar(64) NULL DEFAULT '',
    create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) NULL DEFAULT '',
    update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted bit NOT NULL DEFAULT 0,
    tenant_id bigint NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_wallet_user_tenant ON aigc_wallet(user_id, tenant_id);

CREATE TABLE IF NOT EXISTS aigc_quota_freeze (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    freeze_no varchar(64) NOT NULL,
    wallet_id bigint NOT NULL,
    user_id bigint NOT NULL,
    biz_type varchar(64) NOT NULL,
    biz_id varchar(128) NOT NULL,
    task_id bigint NULL,
    task_no varchar(64) NULL,
    amount decimal(18,6) NOT NULL,
    confirmed_amount decimal(18,6) NOT NULL DEFAULT 0.000000,
    released_amount decimal(18,6) NOT NULL DEFAULT 0.000000,
    status varchar(32) NOT NULL,
    expire_time datetime NULL,
    confirm_time datetime NULL,
    release_time datetime NULL,
    reason varchar(512) NULL,
    creator varchar(64) NULL DEFAULT '',
    create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) NULL DEFAULT '',
    update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted bit NOT NULL DEFAULT 0,
    tenant_id bigint NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_quota_freeze_no ON aigc_quota_freeze(freeze_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_quota_freeze_biz ON aigc_quota_freeze(biz_type, biz_id, tenant_id);

CREATE TABLE IF NOT EXISTS aigc_billing_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_no varchar(64) NOT NULL,
    wallet_id bigint NOT NULL,
    user_id bigint NOT NULL,
    biz_type varchar(64) NOT NULL,
    biz_id varchar(128) NOT NULL,
    record_type varchar(64) NOT NULL,
    title varchar(128) NULL,
    amount decimal(18,6) NOT NULL,
    balance_after decimal(18,6) NOT NULL,
    frozen_balance_after decimal(18,6) NOT NULL,
    freeze_id bigint NULL,
    task_id bigint NULL,
    model_id bigint NULL,
    provider_id bigint NULL,
    currency_type varchar(32) NOT NULL DEFAULT 'POINT',
    price_snapshot varchar(4000) NULL,
    extra_info varchar(4000) NULL,
    creator varchar(64) NULL DEFAULT '',
    create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) NULL DEFAULT '',
    update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted bit NOT NULL DEFAULT 0,
    tenant_id bigint NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_billing_record_no ON aigc_billing_record(record_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_aigc_billing_record_biz_tenant ON aigc_billing_record(biz_type, biz_id, tenant_id);

